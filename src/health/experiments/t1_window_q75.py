"""T1 follow-up: sell the 15:00 to 21:00 window at the forecast's q75.

    uv run python -m src.health.experiments.t1_window_q75
    uv run python -m src.health.experiments.t1_window_q75 --quick

The mechanism reading (``docs/results/t1_mechanism.md``) found that 89.4% of the
Shapley cost in the 15-17 and 18-20 blocks sits in quarter-hours where the median
forecast came in below the realised price. The cheapest test of whether correcting
that pays is on the dispatch side, with no retraining:

* ``median_forecast``: the production dispatch, q50 for both legs all day. It must
  reproduce the saved validation profit, which proves both arms read the same
  inputs and settle the same way.
* ``window_q75_sell``: the same, except that selling from 15:00 to 20:59 local time
  is valued at q75. Buying stays at q50 everywhere, because perfect foresight buys
  more energy in the window than the median schedule, not less.

Both settle at the realised prices, with the same 1 MW / 2 MWh battery and wear.
The criterion was fixed before the run:

    adopt ``window_q75_sell`` only if the mean daily profit difference against
    ``median_forecast`` over the validation days has a 95% moving-block bootstrap
    interval (7-day blocks, 5,000 draws) entirely above zero.

Reported alongside, and not part of the decision: the difference in June to
September and in October to May, capture of perfect foresight, cycles, and how the
window's cash and the whole day's cash by clock block change. Two risks were named
before the run: the median schedule already sells slightly more in the window than
perfect foresight, and a change in the window leaves the midday over-forecast cost
untouched. Validation days only; the hold-out is not read. Results:
``docs/results/t1_window_q75.md`` and ``data/processed/experiments/t1_window_q75_*``.
``--quick`` runs the first 60 days and writes nothing to ``docs/``.
"""

from __future__ import annotations

import argparse
import json
import os
import time
from collections.abc import Mapping
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pandas as pd

from src.config import REPO_ROOT, load_settings
from src.health.experiments.t1_mechanism import (
    BLOCKS,
    SUMMER,
    WINDOW_END_HOUR,
    WINDOW_START_HOUR,
    block_cash,
    mean_interval,
    window_schedule,
)
from src.trading.backtest import load_window, strategy_table, window_days
from src.trading.strategies import MEDIAN_FORECAST, PERFECT_FORESIGHT, Strategy

__all__ = [
    "CANDIDATE",
    "SELL_COLUMN",
    "adopt",
    "main",
    "results_markdown",
    "with_window_sell",
]

PRODUCTION = "lightgbm_conformal"
UPPER = "q75"
SELL_COLUMN = "window_q75_sell"
CANDIDATE = Strategy(SELL_COLUMN, SELL_COLUMN, MEDIAN_FORECAST.buy_column)
RECONCILE_EUR = 0.01
QUICK_DAYS = 60
RESULTS_PATH = REPO_ROOT / "docs" / "results" / "t1_window_q75.md"


def with_window_sell(forecasts: pd.DataFrame, timezone: str) -> pd.DataFrame:
    """Add the sell curve: q75 from 15:00 to 20:59 local time, q50 otherwise."""
    hour = pd.DatetimeIndex(forecasts.index).tz_convert(timezone).hour
    inside = (hour >= WINDOW_START_HOUR) & (hour < WINDOW_END_HOUR)
    median = forecasts[MEDIAN_FORECAST.sell_column]
    return forecasts.assign(**{SELL_COLUMN: forecasts[UPPER].where(inside, median)})


def adopt(difference: Mapping[str, float]) -> bool:
    """The criterion fixed before the run: the whole interval above zero."""
    return bool(difference["low"] > 0)


def _signed(value: float, places: int = 2) -> str:
    return f"{value:+,.{places}f}"


def _interval(item: Mapping[str, float]) -> str:
    return (
        f"{_signed(item['mean'])} ({_signed(item['low'])} to {_signed(item['high'])})"
    )


def _eur(value: float) -> str:
    return f"€{value:,.0f}" if value >= 0 else f"-€{-value:,.0f}"


def results_markdown(summary: Mapping[str, Any]) -> str:
    """The results page; the verdict and every sentence come from the intervals."""
    arms = summary["arms"]
    difference = summary["difference"]
    adopted = adopt(difference["all"])
    lines = [
        "# T1 follow-up: sell the 15:00 to 21:00 window at q75",
        "",
        "Generated by `python -m src.health.experiments.t1_window_q75`. The "
        f"production model's saved validation forecasts, {summary['days']} days "
        f"from {summary['first_day']} to {summary['last_day']}, dispatched for a "
        "1 MW / 2 MWh battery with "
        f"€{summary['wear_eur_per_mwh']:g} wear per MWh discharged. "
        "`median_forecast` values both legs at q50 all day; `window_q75_sell` values "
        "selling from 15:00 to 20:59 local time at q75 and everything else at q50. "
        "Both settle at the realised prices. The median arm reproduces the saved "
        "validation profit to within €0.01.",
        "",
        "Criterion, fixed before the run: adopt `window_q75_sell` only if the mean "
        "daily profit difference against `median_forecast` has a 95% moving-block "
        "bootstrap interval (7-day blocks, 5,000 draws) entirely above zero.",
        "",
        "## Arms",
        "",
        "| arm | profit | capture of perfect foresight | cycles a day | "
        "sold over the day, MWh a day | sold in the window, MWh a day | "
        "planned minus settled, € a day |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in (MEDIAN_FORECAST.name, CANDIDATE.name):
        arm = arms[name]
        lines.append(
            f"| {name} | {_eur(arm['pnl_eur'])} | {100 * arm['capture']:.2f}% | "
            f"{arm['cycles_per_day']:.2f} | {arm['sold_mwh_per_day']:.2f} | "
            f"{arm['window_sold_mwh_per_day']:.2f} | "
            f"{_signed(arm['plan_minus_settled_eur_per_day'])} |"
        )
    lines += [
        "",
        f"Perfect foresight made {_eur(summary['perfect_foresight_pnl_eur'])} on the "
        "same days.",
        "",
        "## window_q75_sell minus median_forecast",
        "",
        "Euros per day, with 95% intervals.",
        "",
        "| measure | all days | June to September | October to May |",
        "|---|---|---|---|",
        f"| daily profit | {_interval(difference['all'])} | "
        f"{_interval(difference['summer'])} | {_interval(difference['winter'])} |",
        f"| cash in the window | {_interval(summary['window_cash']['all'])} | "
        f"{_interval(summary['window_cash']['summer'])} | "
        f"{_interval(summary['window_cash']['winter'])} |",
        "",
        "Cash by clock block over the whole day, euros per day:",
        "",
        "| block | window_q75_sell minus median_forecast |",
        "|---|---|",
    ]
    for name in BLOCKS:
        lines.append(f"| {name} | {_interval(summary['blocks'][name])} |")
    total = difference["all"]["mean"] * difference["all"]["days"]
    verdict = (
        "adopted: the whole interval is above zero"
        if adopted
        else "not adopted: the interval does not lie above zero"
    )
    lines += [
        "",
        "## Verdict",
        "",
        f"`window_q75_sell` is {verdict}. Over the {summary['days']} days it made "
        f"{_eur(total)} against median dispatch, a difference of "
        f"{_interval(difference['all'])} € a day.",
        "",
    ]
    if not adopted and difference["all"]["high"] < 0:
        lines += [
            "The interval lies below zero: selling the window at q75 loses money "
            "against median dispatch.",
            "",
        ]
    return "\n".join(lines)


def _finite(value: Any) -> Any:
    """The summary with NaN written as null, so the file stays strict JSON."""
    if isinstance(value, dict):
        return {key: _finite(item) for key, item in value.items()}
    if isinstance(value, float) and value != value:
        return None
    return value


def _write(path: Path, write: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    partial_path = path.with_name(f".{path.name}.partial")
    write(partial_path)
    os.replace(partial_path, path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Test selling the 15:00 to 21:00 window at the forecast's q75."
    )
    parser.add_argument("--config", type=Path, default=None)
    parser.add_argument(
        "--workers", type=int, default=max(1, (os.cpu_count() or 2) - 1)
    )
    parser.add_argument(
        "--quick", action="store_true", help=f"first {QUICK_DAYS} days only"
    )
    args = parser.parse_args(argv)
    if args.workers < 1:
        parser.error("--workers must be at least 1")

    settings = load_settings(args.config)
    tz = settings.market.timezone
    wear = float(settings.battery.degradation_eur_per_mwh)
    strategies = (PERFECT_FORESIGHT, MEDIAN_FORECAST, CANDIDATE)
    forecasts = with_window_sell(load_window(settings, "validation", PRODUCTION), tz)
    days, skipped = window_days(forecasts, settings, "validation", strategies)
    if args.quick:
        days = days[:QUICK_DAYS]
    if days[-1] >= settings.evaluation.holdout_start:
        raise RuntimeError("the selected days reach the hold-out")
    print(f"dispatching {len(days)} days, {len(skipped)} skipped", flush=True)

    started = time.perf_counter()
    dispatch, pnl, _, failed = strategy_table(
        forecasts, days, strategies, settings.battery, settings, workers=args.workers
    )
    if failed:
        raise RuntimeError(f"dispatch failed on {sorted(failed)}")
    print(f"done in {(time.perf_counter() - started) / 60:.1f} min", flush=True)

    profit = pnl.pivot(index="target_day", columns="strategy", values="pnl_eur")
    saved = pd.read_parquet(
        settings.data.processed_path / "trading" / PRODUCTION / "pnl_daily.parquet"
    ).pivot(index="target_day", columns="strategy", values="pnl_eur")
    missing = sorted(set(profit.index) - set(saved.index))
    if missing:
        raise RuntimeError(f"no saved validation profit for {missing[:3]}")
    drift = float(
        (profit[MEDIAN_FORECAST.name] - saved.loc[profit.index, MEDIAN_FORECAST.name])
        .abs()
        .max()
    )
    if drift > RECONCILE_EUR:
        raise RuntimeError(
            f"the median arm misses the saved validation profit by €{drift:.4f}"
        )

    traded = sorted(profit.index)
    summer = pd.Series(
        pd.to_datetime(pd.Index(traded)).month.isin(sorted(SUMMER)), index=traded
    )
    daily = (profit[CANDIDATE.name] - profit[MEDIAN_FORECAST.name]).loc[traded]
    cycles = pnl.pivot(index="target_day", columns="strategy", values="cycles")
    sold = pnl.pivot(index="target_day", columns="strategy", values="discharged_mwh")
    planned = pnl.pivot(
        index="target_day", columns="strategy", values="planned_value_eur"
    )

    def arm_frames(name: str) -> tuple[pd.DataFrame, pd.DataFrame]:
        chosen = dispatch[dispatch["strategy"] == name]
        return window_schedule(chosen, tz), block_cash(chosen, tz, wear)

    windows, blocks = {}, {}
    for name in (MEDIAN_FORECAST.name, CANDIDATE.name):
        windows[name], blocks[name] = arm_frames(name)

    def window_cash(frame: pd.DataFrame) -> pd.Series:
        return (
            frame["discharge_eur"]
            - frame["charge_eur"]
            - wear * frame["discharged_mwh"]
        )

    cash_change = (
        window_cash(windows[CANDIDATE.name])
        - window_cash(windows[MEDIAN_FORECAST.name])
    ).loc[traded]
    block_change = (blocks[CANDIDATE.name] - blocks[MEDIAN_FORECAST.name]).loc[traded]
    ceiling = float(profit[PERFECT_FORESIGHT.name].sum())

    summary: dict[str, Any] = {
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "model": PRODUCTION,
        "wear_eur_per_mwh": wear,
        "quick": args.quick,
        "days": len(traded),
        "first_day": str(traded[0]),
        "last_day": str(traded[-1]),
        "perfect_foresight_pnl_eur": ceiling,
        "arms": {
            name: {
                "pnl_eur": float(profit[name].sum()),
                "capture": float(profit[name].sum()) / ceiling,
                "cycles_per_day": float(cycles[name].mean()),
                "sold_mwh_per_day": float(sold[name].mean()),
                "plan_minus_settled_eur_per_day": float(
                    (planned[name] - profit[name]).mean()
                ),
                "window_sold_mwh_per_day": float(
                    windows[name]["discharged_mwh"].mean()
                ),
            }
            for name in (MEDIAN_FORECAST.name, CANDIDATE.name)
        },
        "difference": {
            "all": mean_interval(daily),
            "summer": mean_interval(daily, summer),
            "winter": mean_interval(daily, ~summer),
        },
        "window_cash": {
            "all": mean_interval(cash_change),
            "summer": mean_interval(cash_change, summer),
            "winter": mean_interval(cash_change, ~summer),
        },
        "blocks": {name: mean_interval(block_change[name]) for name in BLOCKS},
    }
    summary["adopted"] = adopt(summary["difference"]["all"])

    out = settings.data.processed_path / "experiments"
    prefix = "t1_window_q75_quick" if args.quick else "t1_window_q75"
    _write(out / f"{prefix}_pnl.parquet", pnl.to_parquet)
    _write(
        out / f"{prefix}_summary.json",
        lambda path: path.write_text(
            json.dumps(_finite(summary), indent=2, default=str), encoding="utf-8"
        ),
    )
    page = results_markdown(summary)
    print(page)
    if not args.quick:
        _write(RESULTS_PATH, lambda path: path.write_text(page, encoding="utf-8"))
        print(f"wrote {RESULTS_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
